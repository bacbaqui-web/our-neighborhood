import assert from 'node:assert/strict';
import fs from 'node:fs';
import {generationPoint,currentScene,matchingScene,GENERATION_VERSION,RULESET} from '../outputs/domestic-test/browser-generation/policy.js';
const point=generationPoint({address:'시험 위치',center:[37.62,127.02],radius:50});
assert.equal(point.view.mode,'visible360');
assert.equal(generationPoint({...point,view:null}).view.heading,0);
const saved={browserGenerationVersion:GENERATION_VERSION,ruleset:RULESET,view:point.view,sizeMetres:100,origin:point.center};
assert(currentScene(saved));assert(matchingScene(saved,point));
assert(!currentScene({...saved,browserGenerationVersion:10}));
assert(!currentScene({...saved,view:null}));
assert(!matchingScene(saved,{...point,radius:100}));
for(const radius of [0,75,Infinity,350])assert.throws(()=>generationPoint({...point,radius}));
assert.throws(()=>generationPoint({...point,center:[NaN,127]}));
assert.throws(()=>generationPoint({...point,view:{heading:360}}));
const entry=fs.readFileSync('work/browser-generation/entry.py','utf8');
assert(entry.includes("validate_view(params.get('view') or {})"));
assert(entry.includes("'browserGenerationVersion':11"));
assert(!fs.readFileSync('outputs/domestic-test/map-picker.js','utf8').includes('value="circle"'));
console.log('Unified generation: all callers use visible360; legacy caches cannot bypass rules; invalid inputs rejected.');
