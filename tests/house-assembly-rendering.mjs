import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRegistry} from '../outputs/domestic-test/asset-encyclopedia/registry.js';
import {createDetails} from '../outputs/domestic-test/details.js';
const raw=JSON.parse(fs.readFileSync(new URL('../outputs/domestic-test/asset-encyclopedia/catalog.json',import.meta.url)));
const before=JSON.stringify(raw),registry=createRegistry(raw);
const b={inkObjectId:1,seed:12,points:[[0,0],[8,0],[8,7],[0,7]],top:8.4,base:0,floor:2.8,levels:3,styleIndex:0,frontEdge:0,hasEntry:true};
const render=r=>createDetails([b],()=>0,{structures:[]},{assetRegistry:r});
const g=render(registry),report=g.userData.assemblyReport;
assert.ok(report.decisions.some(d=>d.role==='wall'&&d.selectedId==='part:wall-0'));
assert.ok(report.decisions.some(d=>d.role==='window'&&d.status==='exact'));
assert.ok(report.decisions.some(d=>d.role==='door'&&d.status==='exact'));
assert.equal(report.counts.error,0);
assert.equal(JSON.stringify(raw),before,'registry input is unchanged');
const removed=report.decisions.find(d=>d.role==='window'&&d.requestedId!=='part:white-slider').requestedId;
const missing=render({resolve:id=>id===removed?null:registry.resolve(id)});
assert.ok(missing.userData.assemblyReport.decisions.some(d=>d.requestedId===removed&&d.status==='fallback'&&d.rejected.length));
const none=render({resolve:()=>null});
assert.ok(none.userData.assemblyReport.counts.error>0);
assert.equal(none.userData.windows,0);assert.equal(none.userData.doors,0);
assert.ok(none.children.some(o=>o.isMesh&&o.material.color.getHex()===0xd73b77&&o.userData.noPlacementCollision));
assert.ok(none.userData.assemblyReport.decisions.every(d=>!d.collider));
const legacy=createDetails([b],()=>0);assert.ok(legacy.userData.windows>0);assert.equal(legacy.userData.assemblyReport.decisions.length,0);
console.log('house assembly rendering passed',report.counts);

const narrow=createDetails([{...b,points:[[0,0],[.7,0],[.7,7],[0,7]],hasEntry:false}],()=>0,{structures:[]},{assetRegistry:registry});
assert.ok(narrow.userData.assemblyReport.counts.excluded>0);
assert.equal(narrow.userData.assemblyReport.counts.error,0);
assert.ok(!narrow.children.some(o=>o.isMesh&&o.material.color.getHex()===0xd73b77));
