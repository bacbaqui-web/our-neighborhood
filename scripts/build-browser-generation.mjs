import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const projectRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(new URL('../work/browser-generation/package.json',import.meta.url));
const {build,transform,version}=require('esbuild');
const entry='work/browser-generation/prepare-scene.js';
const output='outputs/domestic-test/browser-generation/prepare-scene.js';
const buildInputs=['scripts/build-browser-generation.mjs','work/browser-generation/package.json','work/browser-generation/package-lock.json'];
const slash=p=>p.split(path.sep).join('/');

export async function bundleGeneration(root=projectRoot){
  root=await fs.realpath(root);
  const sources=new Map();
  const result=await build({
    absWorkingDir:root,entryPoints:[entry],outfile:output,write:false,metafile:true,
    bundle:true,format:'esm',platform:'browser',target:'es2022',charset:'utf8',
    legalComments:'eof',logLevel:'silent',
    plugins:[{name:'canonical-browser-sources',setup(builder){
      builder.onResolve({filter:/^(?:three$|\.{1,2}\/|\/)/},args=>{
        if(args.path==='three')return {path:path.join(root,'outputs/domestic-test/vendor/three.module.js')};
        const [name,...suffix]=args.path.split(/(?=[?#])/);
        if(suffix.length&&!(suffix.length===1&&/^\?v=[\w.-]+$/.test(suffix[0])))throw Error(`Unsupported module URL: ${args.path}`);
        return {path:path.resolve(args.resolveDir||root,name)};
      });
      builder.onLoad({filter:/\.m?js$/},async args=>{
        const source=await fs.readFile(args.path,'utf8');
        sources.set(slash(path.relative(root,args.path)),source);
        if(!source.includes('import.meta.url'))return {contents:source,loader:'js'};
        // Preserve source-relative asset URLs after moving code into the worker bundle.
        // esbuild parses the substitution, so strings/comments are not rewritten.
        const originalURL=slash(path.relative(path.dirname(path.join(root,output)),args.path));
        const transformed=await transform(source,{loader:'js',target:'es2022',define:{'import.meta.url':'__neighborhoodSourceURL'}});
        return {contents:`const __neighborhoodSourceURL=new URL(${JSON.stringify(originalURL)},import.meta.url).href;\n${transformed.code}`,loader:'js'};
      });
    }}],
  });
  for(const name of [...Object.keys(result.metafile.inputs),...buildInputs])sources.set(name,await fs.readFile(path.join(root,name),'utf8'));
  const hash=createHash('sha256').update(`esbuild:${version}\n`);
  for(const [name,source] of [...sources].sort(([a],[b])=>a<b?-1:a>b?1:0)){hash.update(name+'\0');hash.update(source+'\0');}
  return {text:`// Generated by scripts/build-browser-generation.mjs; source SHA-256: ${hash.digest('hex')}\n${result.outputFiles[0].text}`,inputs:[...sources.keys()].sort(),metafile:result.metafile};
}

export async function checkGenerationBundle(root=projectRoot){
  const result=await bundleGeneration(root);
  if(await fs.readFile(path.join(root,output),'utf8')!==result.text)throw Error('브라우저 생성 JavaScript 묶음이 원본과 다릅니다. node scripts/build-browser-generation.mjs로 갱신하세요.');
  return result;
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  if(process.argv.slice(2).some(arg=>arg!=='--check'))throw Error('Usage: node scripts/build-browser-generation.mjs [--check]');
  const check=process.argv.includes('--check');
  const result=check?await checkGenerationBundle():await bundleGeneration();
  if(!check)await fs.writeFile(path.join(projectRoot,output),result.text);
  console.log(`Browser JavaScript bundle ${check?'is current':'written'}: ${Object.keys(result.metafile.inputs).length} modules, esbuild ${version}.`);
}
